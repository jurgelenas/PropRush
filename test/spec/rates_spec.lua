-- Rate curve against Betaflight Configurator's Max Vel figures. RC Rate, Rate and RC Expo in hundredths.

local rate = assert(loadfile("src/SCRIPTS/TOOLS/FPVSim/core/rates.lua"))()

describe("rates", function()
  it("RC 1.00 Rate 0.50 Expo 0.00, full stick", function()
    assert.near(400, rate(1, 100, 50, 0), 0.5)
  end)
  it("RC 2.00 Rate 0.00 Expo 0.42, full stick", function()
    assert.near(400, rate(1, 200, 0, 42), 0.5)
  end)
  it("RC 1.00 Rate 0.00 Expo 0.00, full stick", function()
    assert.near(200, rate(1, 100, 0, 0), 0.5)
  end)
  it("defaults 1.00 / 0.70 / 0.00, full stick both ways", function()
    assert.near(666.7, rate(1, 100, 70, 0), 0.5)
    assert.near(-666.7, rate(-1, 100, 70, 0), 0.5)
  end)
  it("defaults, half stick", function()
    assert.near(100 / 0.65, rate(0.5, 100, 70, 0), 0.5)
  end)
  it("expo 0.42, half stick", function()
    assert.near(200 * (0.5 * 0.125 * 0.42 + 0.5 * 0.58), rate(0.5, 100, 0, 42), 0.5)
  end)
  it("is limited", function()
    assert.near(1998, rate(1, 200, 100, 0), 0.5)
  end)
  it("is zero at centre stick", function()
    assert.equal(0, rate(0, 100, 70, 50))
  end)
end)
